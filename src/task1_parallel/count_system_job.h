#ifndef COUNT_SYSTEM_JOB_H
#define COUNT_SYSTEM_JOB_H
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
// Standard library.
#include <condition_variable>
#include <mutex>
#include <queue>
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
struct CountSystemJob
{
    //---------------------------------------------------------------------------------------//
    // Internal data.
    //---------------------------------------------------------------------------------------//
    size_t m_start;
    size_t m_end;
    //---------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------//
    // Constructor and Destructor.
    //---------------------------------------------------------------------------------------//
    CountSystemJob()
    :   m_start(-1)
    ,   m_end(-1)
    {}

    CountSystemJob(size_t start, size_t end)
    :   m_start(start)
    ,   m_end(end)
    {}
    //---------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------//
    // Copy and Move constructors.
    //---------------------------------------------------------------------------------------//
    CountSystemJob(const CountSystemJob& other)
    {
        m_start = other.m_start;
        m_end = other.m_end;
    }

    CountSystemJob& operator=(const CountSystemJob& other)
    {
        if(this != &other)
        {
            m_start = other.m_start;
            m_end = other.m_end;
        }
        return *this;
    }

    CountSystemJob(CountSystemJob&& other) noexcept
    {
        m_start = other.m_start;
        m_end = other.m_end;
    }

    CountSystemJob& operator=(CountSystemJob&& other) noexcept
    {
        if(this != &other)
        {
            m_start = other.m_start;
            m_end = other.m_end;
        }
        return *this;
    }
    //---------------------------------------------------------------------------------------//
};
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
#endif
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //