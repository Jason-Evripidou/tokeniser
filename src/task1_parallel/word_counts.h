#ifndef WORD_COUNTS_H
#define WORD_COUNTS_H
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
// Internal header files.
#include "word_count.h"

// Standard library.
#include <shared_mutex>
#include <string>
#include <unordered_map>
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
class WordCounts
{
private:
    //---------------------------------------------------------------------------------------//
    std::unordered_map<std::string, WordCount> m_word_counts;
    mutable std::shared_mutex m_shared_mutex;
    //---------------------------------------------------------------------------------------//

public:
    //---------------------------------------------------------------------------------------//
    // Constructor and Destructor.
    //---------------------------------------------------------------------------------------//
    WordCounts() = default;
    //---------------------------------------------------------------------------------------//

    //---------------------------------------------------------------------------------------//
    inline void incrementWordCount(std::string& word)
    {
        std::shared_lock<std::shared_mutex> read_lock(m_shared_mutex);

        // Check word exists in m_word_counts.
        std::unordered_map<std::string, WordCount>::iterator it = m_word_counts.find(word);
        if(it == m_word_counts.end())
        {
            read_lock.unlock();
            
            //-------------------------------------------------------------------------------//
            std::unique_lock<std::shared_mutex> write_lock(m_shared_mutex);

            it = m_word_counts.find(word);
            if(it == m_word_counts.end())
            {
                m_word_counts[word];
                m_word_counts[word].resetCount();
            }

            write_lock.unlock();
            //-------------------------------------------------------------------------------//

            read_lock.lock();
        }

        m_word_counts[word].increment();
    }
    //---------------------------------------------------------------------------------------//
};
// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //


// ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### ##### //
#endif
